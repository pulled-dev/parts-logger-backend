"""Page version stamp + "new version available" check, and upgrading from the
old page without losing unexported parts.

tests/fixtures/old_page_logged_parts.json is what the OLD page (main's
index.html, identical to the live GitHub Pages copy on 15 Oct 2026) wrote to
phone storage: generated by running main's real addPart code in Node for three
part numbers, plus a name the logger corrected on the old page and a Body Panel
item in the old body-panel shape.
"""

import json
import os
import shutil
import subprocess
import sys
from datetime import date

from conftest import fixture_path
from test_frontend_edits import HARNESS, _cut, _sections, _src

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NODE = shutil.which("node")
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import stamp_page_version as spv  # noqa: E402


# ── Version stamp ──────────────────────────────────────────────────────

def test_page_version_stamp_is_current():
    """Fails when index.html changed without re-stamping: run
    python scripts/stamp_page_version.py"""
    with open(os.path.join(ROOT, "index.html"), encoding="utf-8", newline="") as fh:
        text = fh.read()
    assert spv.is_current(text), "run: python scripts/stamp_page_version.py"
    assert spv.current_version(text).count(".") == 1


def test_stamp_hash_ignores_line_endings_and_tracks_content():
    page = '<head><meta name="page-version" content=""></head>\n<p>hi</p>\n'
    stamped = spv.stamp(page, today=date(2026, 10, 15))
    assert spv.current_version(stamped) == "2026-10-15." + spv.content_hash(page)
    assert spv.is_current(stamped) and spv.is_current(stamped.replace("\n", "\r\n"))
    changed = stamped.replace("hi", "hello")
    assert not spv.is_current(changed)
    assert spv.current_version(spv.stamp(changed, today=date(2026, 10, 16))).startswith("2026-10-16.")
    assert spv.stamp(stamped, today=date(2030, 1, 1)) == stamped  # unchanged page keeps its stamp


def test_version_shown_at_bottom_of_page():
    s = _src()
    assert '<div class="page-version" id="page-version"></div>' in s
    assert 'New version available &mdash; tap to reload' in s
    assert "showPageVersion();\ncheckPageVersion();" in s
    assert "serviceWorker" not in s and 'rel="manifest"' not in s  # nothing else caches the page


VERSION_HARNESS = r"""
const out = { fetches: [], saves: 0 };
const OWN = __OWN__;
const els = { 'page-version': { textContent: '' }, 'update-banner': { hidden: true, onclick: null } };
const $ = id => els[id];
const docListeners = {};
const document = {
  visibilityState: 'visible',
  querySelector: sel => (sel === 'meta[name="page-version"]' ? { getAttribute: () => OWN } : null),
  addEventListener: (t, fn) => { docListeners[t] = fn; },
};
const location = { protocol: __PROTOCOL__, origin: 'https://pulled-dev.github.io', pathname: '/parts-logger-backend/',
                   replace: u => { out.replaced = u; } };
let LIVE = __LIVE__;
const fetch = (url, opts) => {
  out.fetches.push({ url, cache: opts && opts.cache });
  if (LIVE === 'FAIL') return Promise.reject(new Error('offline'));
  return Promise.resolve({ ok: true, text: () => Promise.resolve(
    '<!DOCTYPE html><html><head><meta name="page-version" content="' + LIVE + '"></head></html>') });
};
const saveParts = () => { out.saves++; };
__SECTION__
(async () => {
  showPageVersion();
  out.shown = els['page-version'].textContent;
  await checkPageVersion();
  out.bannerHidden = els['update-banner'].hidden;
  if (els['update-banner'].onclick) els['update-banner'].onclick();
  // back to the front a minute later: no second check; much later: checks again
  const n = out.fetches.length;
  docListeners.visibilitychange();
  out.recheckedSoon = out.fetches.length > n;
  lastVersionCheck = Date.now() - VERSION_RECHECK_MS - 1;
  docListeners.visibilitychange();
  await new Promise(r => setTimeout(r, 0));
  out.recheckedLater = out.fetches.length > n;
  process.stdout.write(JSON.stringify(out));
})().catch(e => { console.error(e); process.exit(1); });
"""


def _version(tmp_path, own="2026-10-15.aaaaaaa", live="2026-10-15.aaaaaaa", protocol="https:") -> dict:
    assert NODE, "Node.js is required for the version-check behaviour checks"
    js = (VERSION_HARNESS.replace("__SECTION__", _cut(_src(), "// ── Page version", "// ── Init"))
          .replace("__OWN__", json.dumps(own)).replace("__LIVE__", json.dumps(live))
          .replace("__PROTOCOL__", json.dumps(protocol)))
    script = tmp_path / "version.js"
    script.write_text(js, encoding="utf-8")
    res = subprocess.run([NODE, str(script)], capture_output=True, text=True, encoding="utf-8", timeout=60)
    assert res.returncode == 0, res.stderr
    return json.loads(res.stdout)


def test_same_version_no_banner(tmp_path):
    out = _version(tmp_path)
    assert out["shown"] == "Version 2026-10-15 · aaaaaaa"
    assert out["bannerHidden"] is True and "replaced" not in out
    f = out["fetches"][0]
    assert f["cache"] == "no-store" and f["url"].startswith("https://pulled-dev.github.io/parts-logger-backend/?vcheck=")


def test_out_of_date_shows_banner_and_reload_fetches_new_copy(tmp_path):
    out = _version(tmp_path, live="2026-10-20.bbbbbbb")
    assert out["bannerHidden"] is False
    assert out["replaced"] == "/parts-logger-backend/?v=2026-10-20.bbbbbbb"  # new URL, so not the cached copy
    assert out["saves"] == 1


def test_offline_or_local_file_says_nothing(tmp_path):
    out = _version(tmp_path, live="FAIL")
    assert out["bannerHidden"] is True and "replaced" not in out
    out = _version(tmp_path, protocol="file:", live="2026-10-20.bbbbbbb")
    assert out["fetches"] == [] and out["bannerHidden"] is True


def test_rechecks_when_brought_back_after_a_while(tmp_path):
    out = _version(tmp_path)
    assert out["recheckedSoon"] is False and out["recheckedLater"] is True


# ── Upgrading from the old page ────────────────────────────────────────

def _old_storage() -> str:
    with open(fixture_path("old_page_logged_parts.json"), encoding="utf-8") as fh:
        return json.dumps(json.load(fh))


def _golden_export() -> str:
    with open(fixture_path("index_main_export_section.js"), encoding="utf-8") as fh:
        return fh.read().replace("\r\n", "\n")


def _run_upgrade(tmp_path, scenario: str) -> dict:
    assert NODE, "Node.js is required for the upgrade checks"
    prelude = ("const OLD_STORAGE = " + json.dumps(_old_storage()) + ";\n"
               "const GOLDEN_EXPORT = " + json.dumps(_golden_export()) + ";\n")
    js = HARNESS.replace("__SECTIONS__", _sections()).replace("__SCENARIO__", prelude + scenario)
    script = tmp_path / "upgrade.js"
    script.write_text(js, encoding="utf-8")
    res = subprocess.run([NODE, str(script)], capture_output=True, text=True, encoding="utf-8", timeout=60)
    assert res.returncode == 0, res.stderr
    return json.loads(res.stdout)


def test_new_page_loads_every_part_the_old_page_saved(tmp_path):
    out = _run_upgrade(tmp_path, """
      localStorage.setItem('pulledapart_logged_parts', OLD_STORAGE);
      reload();                                  // first open of the new page
      out.loaded = parts.map(p => [p.part_number, p.description, p.your_price, p.vehicle_ref, p.part_note || '']);
      out.cards = partsList.children.length;
      out.stored = JSON.parse(localStorage.getItem('pulledapart_logged_parts'));
    """)
    old = json.loads(_old_storage())
    assert len(out["loaded"]) == len(old) == 4 and out["cards"] == 4
    assert out["loaded"] == [[p["part_number"], p["description"], p["your_price"], p["vehicle_ref"],
                              p.get("part_note") or ""] for p in old]
    assert out["stored"] == old  # opening the new page doesn't rewrite or drop anything


def test_old_parts_export_byte_for_byte_as_the_old_page_would(tmp_path):
    out = _run_upgrade(tmp_path, """
      localStorage.setItem('pulledapart_logged_parts', OLD_STORAGE);
      reload();
      out.csvNew = await exportNow();
      // the same storage through the OLD page's export code
      localStorage.setItem('pulledapart_logged_parts', OLD_STORAGE);
      reload();
      eval(GOLDEN_EXPORT);
      out.csvOld = await exportNow();
      out.logged = posts.filter(p => p.url.endsWith('/parts/exports'))[0].body.rows;
    """)
    assert out["csvNew"] == out["csvOld"]
    assert "Headlight Switch,15.00,VEH4321" in out["csvNew"]          # the old page's correction survives
    assert "OSF DOOR — small dent" in out["csvNew"]
    rows = {r["part_number"]: r for r in out["logged"]}
    assert rows["6R0941531F"]["final_description"] == "Headlight Switch"
    assert rows["1K0905851"]["edited"] is False and rows[""]["ai_description"] is None


def test_old_parts_can_be_edited_on_the_new_page(tmp_path):
    out = _run_upgrade(tmp_path, """
      localStorage.setItem('pulledapart_logged_parts', OLD_STORAGE);
      reload();
      const id = parts.find(p => p.part_number === '1K0905851').id;
      openEdit(id); type('Ignition Barrel With 2 Keys');
      reload();
      const p = parts.find(x => x.id === id);
      out.desc = p.description; out.ai = p.ai_description; out.edited = p.edited;
      out.count = parts.length;
    """)
    assert out["desc"] == "Ignition Barrel With 2 Keys" and out["ai"] == "IGNITION BARREL"
    assert out["edited"] is True and out["count"] == 4
