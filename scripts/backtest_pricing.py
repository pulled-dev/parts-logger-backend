"""Backtest the pricing engine against our real eBay sales (Phase 7).

    python scripts/backtest_pricing.py                 # uses data/pricing.db
    python scripts/backtest_pricing.py --csv data/ebay-orders/ebay_sales_clean.csv

Rewrites only the block between the AUTO markers in docs/pricing-backtest.md,
so the hand-written interpretation around it is kept. Only aggregate numbers
are written (no individual sales, no part numbers).
"""

from __future__ import annotations

import argparse
import os
import sqlite3
import sys
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from pricing import backtest  # noqa: E402
from pricing.sales_import import import_rows, read_orders_csv  # noqa: E402
from pricing.store import init_pricing_db  # noqa: E402

DOC = os.path.join(ROOT, "docs", "pricing-backtest.md")
START, END = "<!-- AUTO:START -->", "<!-- AUTO:END -->"


def _m(x: dict) -> str:
    if not x or not x["n"]:
        return "– | –"
    return f"{x['mdape']:.1f}% | {x['within']:.1f}%"


def _row(label: str, d: dict) -> str:
    n = d["new"]["n"]
    return f"| {label} | {n} | {_m(d['old'])} | {_m(d['new'])} |"


def render(s: dict, v: dict, end: date, days: int) -> str:
    h = s["head_to_head"]
    out = [
        START,
        f"_Generated by `scripts/backtest_pricing.py` for sales from {date.fromordinal(end.toordinal() - days + 1)} "
        f"to {end} (last {days} days). Error = |suggested − actual total price| / actual. "
        "MdAPE = median absolute % error (lower is better). ±15% = share of sales priced within 15% "
        "(higher is better)._",
        "",
        "### Coverage",
        "",
        "| | Sales |",
        "|---|---|",
        f"| Sales in window | {s['sales_in_window']} |",
        f"| With a part number in the title (engine can be asked) | {s['with_part_number']} |",
        f"| No part number (body panels etc.; neither method applies) | {s['no_part_number']} |",
        f"| Old method had a replayable DB price | {s['old_has_price']} |",
        f"| Engine deliberately gave **no price** (variant-sensitive, \"Check price\") | "
        f"{s['engine_no_price']['count']} |",
        f"| Both methods gave a price (head-to-head set) | {s['both_priced']} |",
        "",
        f"On the {s['engine_no_price']['count']} no-price sales the old method's DB price had MdAPE "
        f"{s['engine_no_price']['old']['mdape']}% and {s['engine_no_price']['old']['within']}% within ±15% "
        f"(n={s['engine_no_price']['old']['n']}). Those sales are excluded from the head-to-head, not counted "
        "as wins or losses for either side.",
        "",
        "### Headline: head-to-head on the same sales (both gave a price)",
        "",
        "| Method | Sales | MdAPE | Within ±15% | Median bias |",
        "|---|---|---|---|---|",
        f"| Old method (BreakerPro DB price) | {h['old']['n']} | {h['old']['mdape']}% | {h['old']['within']}% | "
        f"{s['median_signed_pct']['old']:+.1f}% |",
        f"| New engine (tightened fallback, no market data) | {h['new']['n']} | {h['new']['mdape']}% | {h['new']['within']}% | "
        f"{s['median_signed_pct']['new']:+.1f}% |",
        "",
        f"Sale by sale, the new engine was closer on **{s['new_wins']}** sales, the old method on "
        f"**{s['old_wins']}**, and they tied on {s['ties']}.",
        "",
        f"New engine on every sale with a part number ({s['new_all']['n']}): MdAPE "
        f"{s['new_all']['mdape']}%, within ±15% {s['new_all']['within']}%.",
        "",
        "### Where the engine wins and loses",
        "",
        "| Subset (same sales for both) | Sales | Old MdAPE | Old ±15% | New MdAPE | New ±15% |",
        "|---|---|---|---|---|---|",
        _row("Engine priced from our own sales of this number", s["head_to_head_own_history"]).replace(" | ", " | ", 1),
        _row("Engine had to use a fallback (no own sales)", s["head_to_head_fallback"]),
        _row("Free-postage sales only", s["head_to_head_free_postage"]),
        "",
        "### By engine confidence",
        "",
        "| Confidence | Sales | Old MdAPE | Old ±15% | New MdAPE | New ±15% |",
        "|---|---|---|---|---|---|",
    ]
    for k in ("high", "medium", "low"):
        if k in s["by_confidence"]:
            out.append(_row(k.title(), s["by_confidence"][k]))
    out += ["", "### By engine source (which rung priced it)", "",
            "| Source | Sales | Old MdAPE | Old ±15% | New MdAPE | New ±15% |", "|---|---|---|---|---|---|"]
    for k, d in s["by_source"].items():
        out.append(_row(k, d))
    out += ["", "### Old method by match type", "",
            "| Old match | Sales | Old MdAPE | Old ±15% | New MdAPE | New ±15% |", "|---|---|---|---|---|---|"]
    for k, d in s["old_by_kind"].items():
        out.append(_row(k, d))
    out += ["", "### Over time (leakage check)", "",
            "`vag_parts_db.json` was built on 2026-03-07 from BreakerPro stock exports. The last column is the "
            "share of sales where the old method's exact price is *identical* to that item's own sold price.",
            "", "| Quarter | Sales | Old MdAPE | Old ±15% | New MdAPE | New ±15% | Old price = item's own price |",
            "|---|---|---|---|---|---|---|"]
    for q, d in s["by_quarter"].items():
        out.append(_row(q, d)[:-1] + f"| {d['old_exact_equals_item_pct']:.0f}% |")
    out += ["", "### By part type (15 most common)", "",
            "| Part type | Sales | Old MdAPE | Old ±15% | New MdAPE | New ±15% |", "|---|---|---|---|---|---|"]
    for t in s["by_part_type"][:15]:
        out.append(_row(t["part_type"].lower(), t))
    vh = v["head_to_head"]
    out += ["", "### Diagnostic: opt-in `USE_BREAKERPRO_EXACT` rung (off by default)", "",
            "| Method | Sales | MdAPE | Within ±15% |", "|---|---|---|---|",
            f"| Old method | {vh['old']['n']} | {vh['old']['mdape']}% | {vh['old']['within']}% |",
            f"| Engine + BreakerPro exact rung | {vh['new']['n']} | {vh['new']['mdape']}% | {vh['new']['within']}% |",
            "", "Quarter by quarter with the rung on:", "",
            "| Quarter | Sales | Old MdAPE | Old ±15% | New MdAPE | New ±15% |", "|---|---|---|---|---|---|"]
    for q, d in v["by_quarter"].items():
        out.append(_row(q, d))
    out += ["", END]
    return "\n".join(out)


def load(args) -> sqlite3.Connection:
    if args.csv:
        conn = sqlite3.connect(":memory:")
        conn.row_factory = sqlite3.Row
        init_pricing_db(conn)
        rows, fmt = read_orders_csv(args.csv)
        import_rows(conn, rows, "csv_clean" if fmt == "clean" else "csv_raw")
        return conn
    if not os.path.exists(args.db):
        raise SystemExit(f"{args.db} not found: run scripts/import_ebay_sales.py first, or pass --csv")
    conn = sqlite3.connect("file:" + os.path.abspath(args.db).replace("\\", "/") + "?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    return conn


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Backtest the pricing engine")
    ap.add_argument("--db", default=os.path.join(ROOT, "data", "pricing.db"))
    ap.add_argument("--csv", help="build an in-memory DB from this orders CSV instead")
    ap.add_argument("--end", default=None, help="last sale date to test (default: latest sale)")
    ap.add_argument("--days", type=int, default=365)
    ap.add_argument("--doc", default=DOC)
    args = ap.parse_args(argv)

    conn = load(args)
    end = date.fromisoformat(args.end) if args.end else date.fromisoformat(
        conn.execute("SELECT MAX(sold_date) FROM sold_history").fetchone()[0])
    s = backtest.summarise(backtest.run(conn, end, args.days))
    v = backtest.summarise(backtest.run(conn, end, args.days, breakerpro_exact=True))
    block = render(s, v, end, args.days)

    existing = open(args.doc, encoding="utf-8").read() if os.path.exists(args.doc) else ""
    if START in existing and END in existing:
        doc = existing[: existing.index(START)] + block + existing[existing.index(END) + len(END):]
    else:
        doc = "# Pricing engine backtest\n\n" + block + "\n"
    os.makedirs(os.path.dirname(args.doc), exist_ok=True)
    with open(args.doc, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(doc)
    h = s["head_to_head"]
    print(f"Old MdAPE {h['old']['mdape']}% / ±15% {h['old']['within']}%  vs  "
          f"new MdAPE {h['new']['mdape']}% / ±15% {h['new']['within']}%  (n={h['new']['n']})")
    print(f"Wrote {args.doc}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
